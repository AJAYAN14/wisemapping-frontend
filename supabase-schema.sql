-- ==============================================================================
-- WiseMapping 个人云同步 Supabase 数据库初始化脚本
-- 适用平台：Supabase (PostgreSQL 15+)
-- 功能：单人多设备云端安全同步，无锁模式，全生命周期 RLS 数据隔离保护
-- ==============================================================================

-- 1. 创建思维导图主表
CREATE TABLE IF NOT EXISTS public.mindmaps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL DEFAULT auth.uid(),
    title VARCHAR(255) NOT NULL DEFAULT 'New Mindmap',
    description TEXT,
    starred BOOLEAN NOT NULL DEFAULT FALSE,
    xml TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. 创建标签表与关联表
CREATE TABLE IF NOT EXISTS public.mindmap_labels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL DEFAULT auth.uid(),
    title VARCHAR(50) NOT NULL,
    color VARCHAR(20) NOT NULL DEFAULT '#000000',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.r_label_mindmap (
    mindmap_id BIGINT REFERENCES public.mindmaps(id) ON DELETE CASCADE NOT NULL,
    label_id BIGINT REFERENCES public.mindmap_labels(id) ON DELETE CASCADE NOT NULL,
    PRIMARY KEY (mindmap_id, label_id)
);

-- 3. 创建版本历史表（防止误删，支持回退）
CREATE TABLE IF NOT EXISTS public.mindmap_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mindmap_id BIGINT REFERENCES public.mindmaps(id) ON DELETE CASCADE NOT NULL,
    xml TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ==============================================================================
-- 4. 开启行级安全（Row Level Security），保障纯私有闭环
-- ==============================================================================
ALTER TABLE public.mindmaps ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mindmap_labels ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.r_label_mindmap ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mindmap_history ENABLE ROW LEVEL SECURITY;

-- 只有自己能增删改查自己的导图
CREATE POLICY "Users can manage their own mindmaps"
ON public.mindmaps
FOR ALL
TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

-- 只有自己能增删改查自己的标签
CREATE POLICY "Users can manage their own labels"
ON public.mindmap_labels
FOR ALL
TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

-- 关联表权限
CREATE POLICY "Users can manage label relations on their maps"
ON public.r_label_mindmap
FOR ALL
TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.mindmaps m
        WHERE m.id = r_label_mindmap.mindmap_id AND m.user_id = auth.uid()
    )
);

-- 历史记录权限
CREATE POLICY "Users can view and create history for their maps"
ON public.mindmap_history
FOR ALL
TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.mindmaps m
        WHERE m.id = mindmap_history.mindmap_id AND m.user_id = auth.uid()
    )
);

-- ==============================================================================
-- 5. 自动更新 updated_at 触发器
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER on_mindmap_updated
    BEFORE UPDATE ON public.mindmaps
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

